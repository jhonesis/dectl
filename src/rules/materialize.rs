//! Materialization for the rules subsystem (REQ-rules-001, REQ-rules-005).
//!
//! - `project init --standard` (no `profile.toml` yet): only the universal
//!   set — `.dec/rules/transversal.yaml` (rules with empty `requires`) plus
//!   a read-only copy of `.dec/rules/profile.schema.yaml`. `profiles/` is
//!   intentionally NOT created.
//! - `spec init` / `profile update` (profile known): mirror norm — group the
//!   **resolved active set** by `primary_flag` and write
//!   `.dec/rules/transversal.yaml` + `.dec/rules/profiles/{flag}.yaml`, each
//!   holding **exactly its active rules** (never inactive candidates), plus
//!   the readable `.dec/rules/active-ruleset.md`.
//!   `realtime` is reference-only (`- ref:` pointers, `rules: []` when none
//!   of its cross-referenced rules is active).
//!
//! Rule bodies are copied verbatim from the embedded catalog (same approach
//! as `rules/partition_rules.py`), so the output stays byte-compatible with
//! the reference in `rules/profiles/`. Writes are write-if-changed, so a
//! second run neither re-asks nor re-materializes. Stale profile files
//! (flag now `false`) are removed; an empty `profiles/` dir is removed.

